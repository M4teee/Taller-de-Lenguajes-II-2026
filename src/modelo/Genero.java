package modelo;

/**
 * Enumera los géneros aceptados por los contenidos de la plataforma.
 * Sus valores son cerrados y cada contenido tiene un solo género.
 */
public enum Genero {
    /** Rock producido en Argentina. */
    ROCK_NACIONAL,
    /** Género musical trap. */
    TRAP,
    /** Género musical hip hop. */
    HIP_HOP,
    /** Contenido orientado a público infantil. */
    MUSICA_INFANTIL,
    /** Género musical pop. */
    POP,
    /** Género musical folclore. */
    FOLKLORE,
    /** Género musical cumbia. */
    CUMBIA,
    /** Género musical electrónica. */
    ELECTRONICA,
    /** Relatos de crímenes reales. */
    TRUE_CRIME,
    /** Contenido de humor. */
    HUMOR,
    /** Relatos de ciencia ficción. */
    CIENCIA_FICCION,
    /** Contenido educativo. */
    EDUCATIVO
}
